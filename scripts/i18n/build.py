# Build src/i18n/en-elementary.ts from keys.json + tr-*.txt (index<TAB>English).
import json,glob,re,sys
out={}
for f in sorted(glob.glob('scripts/i18n/tr-*.txt')):
    batch=f.split('tr-')[1].split('-')[0]
    keys=json.load(open('scripts/i18n/keys-'+batch+'.json'))
    for line in open(f,encoding='utf8'):
        line=line.rstrip('\n')
        if not line.strip(): continue
        i,en=(line.split('\t',1)+[''])[:2]
        k=keys[int(i)][0]
        # every slot in the Korean key must appear in the English
        ks=set(re.findall(r'⟨\d+⟩',k)); es=set(re.findall(r'⟨\d+⟩',en))
        if es-ks: print('EXTRA SLOT',i,k,'=>',en); sys.exit(1)
        if ks-es: print('missing slot',i,sorted(ks-es),k[:60])
        if re.search('[가-힣]',en): print('HANGUL LEFT',i,en[:80])
        out[k]=en
def q(s): return "'"+s.replace('\\','\\\\').replace("'","\\'")+"'"
lines=['/** English for elementary lessons, keyed by the Korean text (numbers as ⟨n⟩ slots).',
       ' *  Generated by scripts/i18n/build.py from the harvested sentence list. */',
       'export const EN_ELEMENTARY:Record<string,string>={']
lines+=['  '+q(k)+':'+q(v)+',' for k,v in out.items()]
lines.append('};')
open('src/i18n/en-elementary.ts','w',encoding='utf8').write('\n'.join(lines)+'\n')
print(len(out),'entries')
